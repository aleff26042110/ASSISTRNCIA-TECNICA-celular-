type PartOptions = {
  visual: ComponentVisual;
  accuracy?: ComponentAccuracy;
  sources?: string[];
};

const part = (
  id: string,
  name: string,
  category: string,
  pos: Vec3,
  explode: Vec3,
  size: Vec3,
  color: string,
  stage: number,
  fn: string,
  symptoms: string[],
  options: PartOptions,
): PhoneComponent => ({
  id,
  name,
  category,
  description:
    options.accuracy === "documented"
      ? "Componente documentado para o iPhone 15; a geometria foi simplificada para visualização."
      : "Posição e geometria aproximadas a partir de documentação e desmontagens públicas.",
  function: fn,
  compatibleModel: "iPhone 15 • estudo educacional",
  meshId: id,
  originalPosition: pos,
  explodedPosition: explode,
  size,
  color,
  stage,
  symptoms,
  diagnosisState: "Não analisado",
  visual: options.visual,
  accuracy: options.accuracy ?? "inferred",
  sourceIds: options.sources ?? ["apple-internal-view", "ifixit-teardown"],
});

